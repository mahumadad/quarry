"""AI-assisted nuclei template generation.

Generates nuclei templates on-the-fly for CVEs or findings that lack
existing template coverage.  Templates are validated against fixtures
before use.

Based on CVEngine's templategen model.  Key constraint: generated
templates follow the same quality rules as reviewed templates
(references/nuclei-templates/README.md) — GET-only, AND matchers,
no state-changing requests.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path


TEMPLATE_SKELETON = """\
id: {template_id}
info:
  name: {name}
  author: pentest-plugin-autogen
  severity: {severity}
  description: {description}
  tags: {tags}
  reference:
    - {reference}
  metadata:
    reviewed: false
    autogenerated: true
    generated_at: {generated_at}
    cve_id: {cve_id}
    risk: {risk}
    stacks: {stacks}
    max-request: {max_request}
http:
  - method: GET
    path:
{paths}
    stop-at-first-match: {stop_at_first}
    matchers-condition: and
    matchers:
{matchers}
"""


@dataclass
class TemplateSpec:
    cve_id: str = ""
    product: str = ""
    version_affected: str = ""
    vuln_type: str = ""
    endpoint_patterns: list[str] = field(default_factory=list)
    detection_strings: list[str] = field(default_factory=list)
    severity: str = "info"
    description: str = ""
    reference_url: str = ""
    stacks: list[str] = field(default_factory=list)


@dataclass
class GeneratedTemplate:
    template_id: str = ""
    yaml_content: str = ""
    spec: TemplateSpec = field(default_factory=TemplateSpec)
    validated: bool = False
    validation_result: str = ""
    generated_at: str = ""

    def __post_init__(self):
        if not self.generated_at:
            self.generated_at = datetime.now(timezone.utc).isoformat()


def generate_from_spec(spec: TemplateSpec) -> GeneratedTemplate:
    """Generate a nuclei template YAML from a TemplateSpec.

    The generated template is GET-only with AND matchers.
    It must be validated before use.
    """
    template_id = _make_id(spec)
    paths = _format_paths(spec.endpoint_patterns or ["/"])
    matchers = _format_matchers(spec.detection_strings, spec.vuln_type)
    tags = ",".join(spec.stacks + [spec.vuln_type, "autogenerated"])
    if spec.cve_id:
        tags = f"{spec.cve_id.lower()},{tags}"

    yaml_content = TEMPLATE_SKELETON.format(
        template_id=template_id,
        name=f"{spec.product} {spec.vuln_type} Detection" if spec.product else f"{spec.cve_id} Detection",
        severity=spec.severity,
        description=spec.description or f"Auto-generated detection for {spec.cve_id or spec.vuln_type}",
        tags=tags,
        reference=spec.reference_url or "https://nvd.nist.gov/vuln/detail/" + spec.cve_id if spec.cve_id else "N/A",
        generated_at=datetime.now(timezone.utc).isoformat(),
        cve_id=spec.cve_id,
        risk="safe",
        stacks=",".join(spec.stacks),
        max_request=len(spec.endpoint_patterns) or 1,
        paths=paths,
        stop_at_first="true" if len(spec.endpoint_patterns) > 3 else "false",
        matchers=matchers,
    )

    return GeneratedTemplate(
        template_id=template_id,
        yaml_content=yaml_content,
        spec=spec,
    )


def generate_from_cve(cve_id: str, product: str, version: str,
                      advisory_text: str) -> GeneratedTemplate:
    """Generate a template from CVE details and advisory text.

    Extracts endpoint patterns and detection strings from the advisory.
    This is a heuristic — the template needs validation.
    """
    endpoints = _extract_endpoints(advisory_text)
    detection = _extract_detection_strings(advisory_text, product)
    vuln_type = _infer_vuln_type(advisory_text)

    spec = TemplateSpec(
        cve_id=cve_id,
        product=product,
        version_affected=version,
        vuln_type=vuln_type,
        endpoint_patterns=endpoints or ["/"],
        detection_strings=detection,
        severity=_infer_severity(advisory_text),
        description=f"Detection for {cve_id} in {product} {version}",
        reference_url=f"https://nvd.nist.gov/vuln/detail/{cve_id}",
        stacks=_infer_stacks(product),
    )

    return generate_from_spec(spec)


def validate_template_syntax(template: GeneratedTemplate) -> tuple[bool, list[str]]:
    """Validate generated template against quality rules.

    Checks:
    1. Has id, info, http sections
    2. Only GET method
    3. matchers-condition: and
    4. Paths use {{BaseURL}}/ prefix
    5. No external hosts or redirects
    6. Has at least status + content matcher
    """
    errors = []
    content = template.yaml_content

    if "id:" not in content:
        errors.append("Missing template id")
    if "info:" not in content:
        errors.append("Missing info section")
    if "http:" not in content:
        errors.append("Missing http section")

    if "method: POST" in content or "method: PUT" in content or "method: DELETE" in content:
        errors.append("Only GET method allowed in autogenerated templates")

    if "matchers-condition: and" not in content:
        errors.append("matchers-condition must be 'and'")

    if "{{BaseURL}}" not in content:
        errors.append("Paths must use {{BaseURL}}/ prefix")

    path_lines = re.findall(r'- "(.+?)"', content)
    for p in path_lines:
        if not p.startswith("{{BaseURL}}"):
            errors.append(f"Path does not start with {{{{BaseURL}}}}: {p}")
        if "://" in p.replace("{{BaseURL}}", ""):
            errors.append(f"External URL in path: {p}")

    has_status_matcher = "type: status" in content
    has_content_matcher = "type: word" in content or "type: regex" in content
    if not (has_status_matcher and has_content_matcher):
        errors.append("Must have both status and content matchers")

    template.validated = len(errors) == 0
    template.validation_result = "PASS" if not errors else f"FAIL: {'; '.join(errors)}"
    return (len(errors) == 0, errors)


def save_template(template: GeneratedTemplate, output_dir: Path) -> Path:
    """Save a validated template to disk.

    Autogenerated templates go to a separate directory from reviewed ones.
    """
    if not template.validated:
        raise ValueError("Cannot save unvalidated template")

    autogen_dir = output_dir / "autogenerated"
    autogen_dir.mkdir(parents=True, exist_ok=True)
    path = autogen_dir / f"{template.template_id}.yaml"
    path.write_text(template.yaml_content)
    return path


# --- Internal helpers ---

def _make_id(spec: TemplateSpec) -> str:
    parts = []
    if spec.cve_id:
        parts.append(spec.cve_id.lower())
    if spec.product:
        parts.append(re.sub(r"[^a-z0-9]+", "-", spec.product.lower()).strip("-"))
    parts.append("autogen")
    return "-".join(parts)


def _format_paths(endpoints: list[str]) -> str:
    lines = []
    for ep in endpoints:
        if not ep.startswith("/"):
            ep = "/" + ep
        lines.append(f'      - "{{{{BaseURL}}}}{ep}"')
    return "\n".join(lines) or '      - "{{BaseURL}}/"'


def _format_matchers(detection_strings: list[str], vuln_type: str) -> str:
    lines = [
        "      - type: status",
        "        status: [200]",
    ]
    if detection_strings:
        lines.extend([
            "      - type: word",
            "        part: body",
            "        words:",
        ])
        for ds in detection_strings[:5]:
            lines.append(f'          - "{ds}"')
        if len(detection_strings) > 1:
            lines.append("        condition: or")
    return "\n".join(lines)


def _extract_endpoints(text: str) -> list[str]:
    patterns = re.findall(r'(?:/[\w\-./]+){2,}', text)
    seen = set()
    unique = []
    for p in patterns:
        if p not in seen and not p.endswith(('.js', '.css', '.png', '.jpg')):
            seen.add(p)
            unique.append(p)
    return unique[:8]


def _extract_detection_strings(text: str, product: str) -> list[str]:
    candidates = []
    if product:
        candidates.append(product)
    version_patterns = re.findall(r'\b\d+\.\d+(?:\.\d+)*\b', text)
    for v in version_patterns[:3]:
        candidates.append(v)
    error_strings = re.findall(r'"([^"]{10,60})"', text)
    candidates.extend(error_strings[:3])
    return candidates[:5]


def _infer_vuln_type(text: str) -> str:
    text_lower = text.lower()
    mapping = {
        "remote code execution": "rce",
        "sql injection": "sqli",
        "cross-site scripting": "xss",
        "path traversal": "path-traversal",
        "directory traversal": "path-traversal",
        "information disclosure": "info-disclosure",
        "authentication bypass": "auth-bypass",
        "server-side request forgery": "ssrf",
        "deserialization": "deserialization",
        "command injection": "command-injection",
        "privilege escalation": "privilege-escalation",
        "denial of service": "dos",
    }
    for phrase, vtype in mapping.items():
        if phrase in text_lower:
            return vtype
    return "misconfiguration"


def _infer_severity(text: str) -> str:
    text_lower = text.lower()
    if "critical" in text_lower or "rce" in text_lower or "remote code execution" in text_lower:
        return "critical"
    if "high" in text_lower:
        return "high"
    if "medium" in text_lower:
        return "medium"
    return "info"


def _infer_stacks(product: str) -> list[str]:
    product_lower = product.lower()
    stack_map = {
        "apache": ["apache"], "nginx": ["nginx"], "iis": ["aspnet"],
        "tomcat": ["java", "tomcat"], "spring": ["java", "spring"],
        "django": ["python", "django"], "flask": ["python", "flask"],
        "fastapi": ["python", "fastapi"], "rails": ["ruby", "rails"],
        "express": ["nodejs", "express"], "next": ["nodejs", "nextjs"],
        "laravel": ["php", "laravel"], "wordpress": ["php", "wordpress"],
        "fortinet": ["fortinet"], "palo alto": ["paloalto"],
    }
    for key, stacks in stack_map.items():
        if key in product_lower:
            return stacks
    return []
